"""Write the No Russian (airport) co-op patches, taking every replaced text from the extracted
game scripts so it matches byte for byte.
Usage: python -I gen_airport_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch  # noqa: E402
from seek_patch import seek_everywhere  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]
M = 'maps\\_mw2coop_airport::'

# ---------------------------------------------------------------- airport_code.gsc
p = Patch(gsc_root, 'airport/maps/airport_code.gsc', out_dir)
p.note('''1. Elevator: player 2 gets his own place at the back wall beside player 1, his view held
   the same way, and is let go with him.''')
p.subst('airport_vision_elevator', 'level.player playerlinkto( node, undefined, 1, 0,0,0,0,0 );',
        'level.player playerlinkto( node, undefined, 1, 0,0,0,0,0 );\n\t' + M + 'partner_in_elevator( node );')
p.subst('airport_vision_elevator', 'level.player SetPlayerAngles( angles );',
        'level.player SetPlayerAngles( angles );\n\t' + M + 'partner_out_of_elevator( angles );')

p.note('''2. Ending: either player can be the one at the van; the death scenes run on the player they
   are for (self, the model's player), so Makarov can shoot both.''')
p.subst('grab_player_if_he_gets_close', 'if ( player_ready_for_ending( origin ) )',
        'if ( ' + M + 'someone_ready_for_ending( origin ) )')
for fn in ('player_ready_for_ending', 'player_would_see_ending', 'escape_animate_player_death',
           'escape_animate_player_death2'):
    p.subst(fn, 'level.player', 'self')
p.subst('player_loses_speed', 'level.player setmovespeedscale( speed );',
        'foreach ( p in ' + M + 'slowed_players() )\n\t\t\tp setmovespeedscale( speed );')
for fn in ('escape_animate_player_death', 'escape_animate_player_death2'):
    p.subst(fn, 'level.playermodel = model;', 'level.playermodel = model;\n\tmodel.mw2coop_victim = self;')
p.subst('escape_draw_blood', 'level.player SetContents( 0 );', 'self.mw2coop_victim SetContents( 0 );')
p.note('''3. Enemies sent at "the player" (the tarmac sniper, the final guys, the team once the cover
   is blown) go for the closest player still up (maps\\_mw2coop::seek_player).''')
seek_everywhere(p)
p.note('''4. The cover: firing at Makarov's squad already counts for either player. Straying from the
   squad counts for the player furthest from it, both players' grenades count, and when the
   cover is blown Makarov shoots both (maps\\_mw2coop_airport: in co-op the revive system stays
   on and the mission fails after his shots).''')
p.subst('friendly_fire_distance_check', 'Distance( level.team_origin, self.origin )',
        M + 'farthest_from( level.team_origin, self )')
p.subst('friendly_fire', 'level.player thread friendly_fire_nade_throw();', 'array_thread( level.players, ::friendly_fire_nade_throw );')
p.subst('friendly_fire', 'level.player EnableDeathShield( false );\n\tlevel.player EnableHealthShield( false );',
        M + 'cover_blown_shields();')
shots = ''.join('\tMagicBullet( member.weapon, member GetTagOrigin( "tag_flash" ), level.player.origin + ( 0, 0, 64 ) );\n' + ('\twait .2;\n' if i < 3 else '')
                for i in range(4))
p.subst('friendly_fire', shots + '\tlevel.player Kill();\n', '\t' + M + 'makarov_kills_players( member );\n')
p.note('''5. The squad's line of fire (lobby, massacre): warning shots at the feet of whichever player
   stands in it, and the one who walks on into it dies, not always player 1
   (maps\\_mw2coop_airport::in_line_of_fire, line_of_fire_kill).''')
p.subst('player_line_of_fire', '\t\tif ( Distance( self.origin, level.player.origin ) < self.radius )',
        '\t\tmw2coop_target = ' + M + 'in_line_of_fire( self );\n\t\tif ( isdefined( mw2coop_target ) )')
p.subst('player_line_of_fire', 'level.player', 'mw2coop_target')


def kill_chain(trigger, abort):
    """The level's add_wait( trigger ) / add_abort( flag ) / level.player add_call( Kill ) chain."""
    return ('\tadd_wait( ::trigger_wait_targetname, "' + trigger + '" );\n\tadd_abort( ::flag_wait, "' + abort + '" );\n'
            '\tlevel.player add_call( ::Kill );\n\tthread do_wait();\n',
            '\tthread ' + M + 'line_of_fire_kill( "' + trigger + '", "' + abort + '" );\n')


p.subst('massacre_killers_shotgun', *kill_chain('massacre_line_of_fire_trig_final', 'massacre_line_of_fire_done'))
p.write('airport_code.gsc.patch', '''
mw2coop patch for maps/airport_code.gsc (No Russian, Modern Warfare 2, 64-bit Steam build)
Generated by tools/gen_airport_patches.py from the game's own script; do not edit by hand.
Co-op logic lives in mw2coop/scripts/maps/_mw2coop_airport.gsc. Outside a co-op campaign session
every change does what the original did (the player is level.player there).
''')

# ---------------------------------------------------------------- airport.gsc
a = Patch(gsc_root, 'airport/maps/airport.gsc', out_dir)
a.note('''1. Ending: both players stand; Makarov shoots the player at the van (or the nearer one), then
   turns and shoots the other.''')
for call in ('allowcrouch( false );', 'allowprone( false );', 'setstance( "stand" );'):
    a.subst('escape_end_sequence', 'level.player ' + call, 'foreach ( p in level.players )\n\t\tp ' + call)
a.subst('escape_end_sequence', 'if ( flag( "player_ready_for_proper_ending" ) )\n\t\tescape_animate_player_death();\n\telse\n\t\tescape_animate_player_death2();',
        M + 'ending_deaths();')
a.subst('escape_end_sequence', 'van thread anim_loop_solo( level.vanmate, "end_get_in_idle", "stop_loop", "origin_animate_jnt" );',
        M + 'vanmate_idle( van );')
a.note('''2. Each shot hits its victim: his sounds, damage and white flash; the death vision with the
   last shot.''')
a.subst('escape_kill_player', 'flag_set( "escape_player_shot" );', 'flag_set( "escape_player_shot" );\n\tvictim = ' + M + 'victim();')
a.subst('escape_kill_player', 'level.player', 'victim')
a.subst('escape_kill_player', 'create_client_overlay( "white", 1 );', 'create_client_overlay( "white", 1, victim );')
a.subst('escape_kill_player', 'set_vision_set( "airport_death", 10 );', M + 'death_vision();')
a.note('''3. The squad's line of fire in the lobby: the player who walks into it dies, not always player 1
   (maps\\_mw2coop_airport::line_of_fire_kill).''')
a.subst('intro_civilians', *kill_chain('intro_line_of_fire_trig_final', 'lobby_to_stairs_go'))
a.note('''4. The level ends and the next mission starts after a restart at a co-op checkpoint too: the
   level only went on from its default start ("DEVELOPER: END OF SCRIPTED LEVEL" otherwise),
   and a checkpoint is a start point (maps\\_mw2coop::ending_goes_on).''')
a.subst('escape_main', 'is_default_start()', 'maps\\_mw2coop::ending_goes_on()')
a.write('airport.gsc.patch', '''
mw2coop patch for maps/airport.gsc (No Russian, Modern Warfare 2, 64-bit Steam build)
Generated by tools/gen_airport_patches.py from the game's own script; do not edit by hand.
Co-op logic lives in mw2coop/scripts/maps/_mw2coop_airport.gsc. Outside a co-op campaign session
every change does what the original did (the victim is level.player there).
''')
