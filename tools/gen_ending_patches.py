"""Write the ending map (knife fight, museum credits) co-op patches, taking every replaced text
from the extracted game scripts so it matches byte for byte.
Usage: python -I gen_ending_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]
M = 'maps\\_mw2coop_ending::'

e = Patch(gsc_root, 'ending/maps/ending.gsc', out_dir)
e.note('''1. The map's mode: in co-op an unknown or empty ui_char_museum_mode means "credits_1" (from
   af_chase: knife fight, then credits).''')
e.subst('main', 'level.level_mode =  getdvar( "ui_char_museum_mode" );', 'level.level_mode = ' + M + 'museum_mode();')
e.write('ending.gsc.patch', '''
mw2coop patch for maps/ending.gsc (ending: knife fight and museum credits, Modern Warfare 2,
64-bit Steam build). Generated by tools/gen_ending_patches.py; do not edit by hand.
Co-op logic lives in mw2coop/scripts/maps/_mw2coop_ending.gsc.
''')

# ---------------------------------------------------------------- char_museum.gsc (the credits: the camera flight through the museum)
m = Patch(gsc_root, 'ending/maps/char_museum.gsc', out_dir)
m.note('''1. The credits' camera carries both players: both are linked to it, held and unarmed, both see the black
   screen it starts from (only player 1 was).''')
for fn in ('start_common', 'start_black'):
    m.subst(fn, 'level.player allowcrouch( false );', 'foreach ( mw2coop_p in level.players )\n\t\tmw2coop_p allowcrouch( false );')
    m.subst(fn, 'level.player allowprone( false );', 'foreach ( mw2coop_p in level.players )\n\t\tmw2coop_p allowprone( false );')
    m.subst(fn, 'level.player TakeAllWeapons();', 'foreach ( mw2coop_p in level.players )\n\t\tmw2coop_p TakeAllWeapons();')
    m.subst(fn, 'level.black = create_client_overlay( "black", 1 );', 'level.black = create_client_overlay( "black", 1 );\n\t' + M + 'museum_black();')
m.subst('start_common', 'level.player playerlinkto( level.camera, undefined, 1, 0,0,0,0,0 );', M + 'museum_link( level.camera );')
m.subst('start_common', 'level.player delaycall( .1, ::freezecontrols, true );',
        'foreach ( mw2coop_p in level.players )\n\t\tmw2coop_p delaycall( .1, ::freezecontrols, true );')
m.subst('start_black', 'level.player DisableWeapons();', 'foreach ( mw2coop_p in level.players )\n\t\tmw2coop_p DisableWeapons();')
m.subst('start_black', 'level.player FreezeControls( true );', 'foreach ( mw2coop_p in level.players )\n\t\tmw2coop_p FreezeControls( true );')
m.subst('player_lerp_eq', 'level.player SetEqLerp( .05, level.eq_main_track );',
        'foreach ( mw2coop_p in level.players )\n\t\tmw2coop_p SetEqLerp( .05, level.eq_main_track );')
m.subst('start_black', 'level.player SetEqLerp( .05, level.eq_main_track );',
        'foreach ( mw2coop_p in level.players )\n\t\tmw2coop_p SetEqLerp( .05, level.eq_main_track );')
m.subst('fade_from_black', 'level.black.alpha = 0;', 'level.black.alpha = 0;\n\t' + M + 'museum_black_fade( 0, 2 );')
m.write('char_museum.gsc.patch', '''
mw2coop patch for maps/char_museum.gsc (Museum, Modern Warfare 2, 64-bit Steam build). Generated by
tools/gen_ending_patches.py; do not edit by hand.
Co-op logic lives in mw2coop/scripts/maps/_mw2coop_ending.gsc.
''')

